#!/usr/bin/env python3
"""Build the v4 Lucide icon sprite from a pinned lucide-static package.

Usage: python3 tools/build_icons_v4.py <path/to/lucide-static/package>

Writes v4/assets/icons/sprite.svg (reference copy) and v4/assets/js/icons.js, which injects the same
<symbol>s into the page — external <use href="sprite.svg#…"> is blocked on file:// in Chromium.
Add a name to ICONS and re-run to add an icon. Source/licence: v4/assets/icons/SOURCE.md.
"""
import json
import pathlib
import re
import sys

VERSION = "0.460.0"
ICONS = [
    # services (docs/v4/visual-direction.md §6)
    "sparkles", "message-circle", "globe", "bot", "server", "database", "folder", "at-sign", "mail", "qr-code",
    # UI
    "arrow-right", "arrow-up-right", "menu", "x", "check", "chevron-down", "plus", "minus", "lock", "power",
    "wallet", "calendar-clock", "refresh-cw", "pause", "bell", "arrow-up-down", "receipt", "languages",
    "workflow", "blocks", "newspaper", "book-open", "clock", "building-2", "search", "sliders-horizontal",
    "rotate-ccw", "send", "copy", "message-square", "shield-check", "chevron-right", "users", "file-text", "landmark",
    "gauge", "circle-pause",
    # console: NAT server, SSH, app usage, chat export, password show/hide, app connections (22 Nov 2026)
    "network", "terminal", "activity", "download", "eye", "eye-off", "plug",
    # Chat AI attachments (22 Nov 2026)
    "paperclip", "image", "mic", "video",
]

ROOT = pathlib.Path(__file__).resolve().parent.parent / "v4" / "assets"


def main():
    src = pathlib.Path(sys.argv[1]) / "icons"
    symbols = []
    for name in ICONS:
        svg = (src / f"{name}.svg").read_text()
        body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
        body = re.sub(r"\s+", " ", body).replace(" />", "/>").strip()
        symbols.append(f'<symbol id="i-{name}" viewBox="0 0 24 24">{body}</symbol>')
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.75" '
              'stroke-linecap="round" stroke-linejoin="round">' + "".join(symbols) + "</svg>")
    (ROOT / "icons" / "sprite.svg").write_text(f"<!-- Lucide v{VERSION} (ISC) — generated by tools/build_icons_v4.py -->\n{sprite}\n")
    (ROOT / "js" / "icons.js").write_text(
        f"/* Lucide v{VERSION} (ISC) icon sprite — generated by tools/build_icons_v4.py, do not edit. */\n"
        "(() => {\n"
        f"  const sprite = {json.dumps(sprite)};\n"
        "  const host = document.createElement('div');\n"
        "  host.hidden = true;\n"
        "  host.innerHTML = sprite.replace('<svg ', '<svg aria-hidden=\"true\" ');\n"
        "  document.body.prepend(host);\n"
        "})();\n")
    print(f"{len(ICONS)} icons")


if __name__ == "__main__":
    main()
